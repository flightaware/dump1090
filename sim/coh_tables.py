# Generates dsp/helpers/demod2400x_coh_tables.h: Q15 phasor tables for the coherent
# decoder (coherent_decode starch kernel). Run from the repository root:
#   python3 sim/coh_tables.py > dsp/helpers/demod2400x_coh_tables.h
# Rounding is floor(x + 0.5) in double precision, so the header is the same everywhere.
import math

CHIP_RATE = 2e6
BLOCK, NBLOCKS = 8, 7                               # 7 blocks of 8 bits = 56 bits
BINS, BINS_PAD, FINE = 32, 32, 8
BIN_HZ = 4000.0                                     # coarse bin spacing (128 kHz / 32)
FINE_BINS = (BINS - 1) * FINE + 1
# Wide search, first stage: 2-bit blocks (2 us apart, unambiguous to +-250 kHz), 16 bins
# 31.25 kHz apart, centres +-15.6 .. +-234.4 kHz (none at 0 Hz); WBLK blocks per half
WBITS, WBLK, WBINS = 2, 28, 16
WBIN_HZ = 31250.0
# Bin centres are symmetric about 0 Hz with none at 0 Hz: +-2, +-6, .. +-62 kHz, so a
# DC offset left by the SDR falls between bins 15 and 16 rather than on a bin centre.
# Fine frequency f (0 .. FINE_BINS-1) is BIN_HZ * (f / FINE - (BINS - 1) / 2).

def bin_w(j):
    """Coarse bin j as radians per chip."""
    return 2 * math.pi * BIN_HZ * (j - (BINS - 1) / 2.0) / CHIP_RATE

def fine_w(f):
    """Fine frequency f as radians per chip."""
    return 2 * math.pi * BIN_HZ * (f / FINE - (BINS - 1) / 2.0) / CHIP_RATE

def q15(v):
    return int(math.floor(32767 * v + 0.5))

def rows(vals, per=10):
    return ',\n'.join('    ' + ', '.join('%6d' % v for v in vals[i:i + per]) for i in range(0, len(vals), per))

print('''// Generated by sim/coh_tables.py; do not edit.
// Q15 phasor tables for the DEMOD_2400X coherent decoder (coherent_decode).

#ifndef DEMOD2400X_COH_TABLES_H
#define DEMOD2400X_COH_TABLES_H

#include <stdint.h>

#define COH_BLOCK      %d       // bits per block in the frequency search (one byte)
#define COH_NBLOCKS    %d       // blocks over the first 56 bits
#define COH_BINS       %d      // coarse frequency bins, centres +-2 .. +-62 kHz (none at 0 Hz)
#define COH_BINS_PAD   %d      // padded to a multiple of 8 (padding phasors are 0)
#define COH_BIN_HZ     %.1f  // coarse bin spacing
#define COH_FINE       %d       // fine steps per coarse bin
#define COH_FINE_BINS  %d     // fine frequencies: BIN_HZ * (f / FINE - (BINS - 1) / 2)
#define COH_WBITS      %d       // bits per block in the wide first stage
#define COH_WBLK       %d      // such blocks per half (two pieces of WBLK / 2)
#define COH_WBINS      %d      // wide bins, centres +-15.6 .. +-234.4 kHz (none at 0 Hz)
#define COH_WBIN_HZ    %.1f // wide bin spacing
''' % (BLOCK, NBLOCKS, BINS, BINS_PAD, BIN_HZ, FINE, FINE_BINS, WBITS, WBLK, WBINS, WBIN_HZ))

# Coarse search: e^{-j w_j t_m}, w_j bin frequency, t_m block centre in chips; [block][bin]
for part, fn in (('RE', math.cos), ('IM', math.sin)):
    print('// e^{-j w t}: %s part, [block][bin]' % ('real' if part == 'RE' else 'imaginary'))
    print('static const int16_t coh_bin_%s[COH_NBLOCKS][COH_BINS_PAD] __attribute__((aligned(16))) = {' % part.lower())
    for m in range(NBLOCKS):
        t = 2 * (m * BLOCK + (BLOCK - 1) / 2.0)
        vals = [q15(fn(-bin_w(j) * t)) for j in range(BINS)] + [0] * (BINS_PAD - BINS)
        print('  {\n' + rows(vals) + '\n  },')
    print('};\n')

def wbin_w(k):
    """Wide bin k as radians per chip."""
    return 2 * math.pi * WBIN_HZ * (k - (WBINS - 1) / 2.0) / CHIP_RATE

# Wide search: e^{-j w_k t_m}, t_m the centre of 2-bit block m from the start of the half,
# in chips; [block][bin]. The first stage uses rows 0 .. WBLK/2 - 1 for both pieces
for part, fn in (('RE', math.cos), ('IM', math.sin)):
    print('// Wide search e^{-j w t}: %s part, [2-bit block][bin]' % ('real' if part == 'RE' else 'imaginary'))
    print('static const int16_t coh_wide_%s[COH_WBLK][COH_WBINS] __attribute__((aligned(32))) = {' % part.lower())
    for m in range(WBLK):
        t = 2 * (m * WBITS + (WBITS - 1) / 2.0)
        vals = [q15(fn(-wbin_w(k) * t)) for k in range(WBINS)]
        print('  {\n' + rows(vals, 8) + '\n  },')
    print('};\n')

# The same phasors transposed, [bin][2-bit block], for rotating all blocks by one bin
# (coh_wide_regroup); padded to 32 blocks with zeros
for part, fn in (('RE', math.cos), ('IM', math.sin)):
    print('// Wide search e^{-j w t}: %s part, [bin][2-bit block] (transposed, padded)' % ('real' if part == 'RE' else 'imaginary'))
    print('static const int16_t coh_widet_%s[COH_WBINS][32] __attribute__((aligned(32))) = {' % part.lower())
    for k in range(WBINS):
        vals = [q15(fn(-wbin_w(k) * 2 * (m * WBITS + (WBITS - 1) / 2.0))) for m in range(WBLK)] + [0] * (32 - WBLK)
        print('  {\n' + rows(vals, 8) + '\n  },')
    print('};\n')

# Wide bins: e^{-j w} (one chip) and e^{-j 2w} (one bit); [bin][re, im]
for name, mult in (('chip', 1), ('bit', 2)):
    pairs = ['{ %6d, %6d }' % (q15(math.cos(-mult * wbin_w(k))), q15(math.sin(-mult * wbin_w(k)))) for k in range(WBINS)]
    print('// e^{-j %sw} for each wide bin: re, im' % ('' if mult == 1 else '2'))
    print('static const int16_t coh_wide_%s[COH_WBINS][2] = {' % name)
    print(',\n'.join('    ' + ', '.join(pairs[i:i + 4]) for i in range(0, len(pairs), 4)))
    print('};\n')

# Fine frequencies: e^{-j w} (one chip) and e^{-j 2w} (one bit); [fine][re, im]
for name, mult in (('chip', 1), ('bit', 2)):
    pairs = []
    for f in range(FINE_BINS):
        w = fine_w(f)
        pairs.append('{ %6d, %6d }' % (q15(math.cos(-mult * w)), q15(math.sin(-mult * w))))
    print('// e^{-j %sw} for each fine frequency: re, im' % ('' if mult == 1 else '2'))
    print('static const int16_t coh_fine_%s[COH_FINE_BINS][2] = {' % name)
    print(',\n'.join('    ' + ', '.join(pairs[i:i + 5]) for i in range(0, len(pairs), 5)))
    print('};\n')

print('#endif')
